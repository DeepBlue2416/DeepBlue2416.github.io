// scripts/pages.js — страницы услуг: Trade-In, кредит, гарантия, доставка,
// контакты.
//
// Зачем они нужны отдельными адресами. Запросы «трейд ин айфон таганрог»,
// «айфон в рассрочку таганрог», «гарантия на айфон» ищут не каталог, а условие
// покупки. Пока такой текст лежит блоком на главной, поиску нечего показать:
// у блока нет своего адреса, заголовка и разметки. У конкурента под каждую
// услугу своя страница — это одна из причин, почему он собирает запросы,
// которых у нас нет вовсе.
//
// Страницы собираются из того же шаблона, что и карточка товара, поэтому
// шапка, подвал, контакты и счётчик у них общие с сайтом.

