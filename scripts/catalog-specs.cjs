function addIphone18() {
  const models = [
    { series: "iPhone 18 Pro", order: 1817, isMax: false, storages: ["256 ГБ", "512 ГБ", "1 ТБ"] },
    { series: "iPhone 18 Pro Max", order: 1818, isMax: true, storages: ["256 ГБ", "512 ГБ", "1 ТБ", "2 ТБ"] },
  ];
  let added = 0;
  for (const m of models) {
    for (const st of m.storages) {
      for (const c of COLORS_18) {
        const key = `${m.series}|${st}|${c.ru}`;
        const supplier = SUPPLIER_18[key] || 0;
        const cash = supplier ? to990(supplier + MARKUP) : 0;
        const id = `iphone-${slug(m.series)}-${slug(c.ru)}-${slug(st)}-sim-esim`;
        if (products.some((p) => p.id === id)) continue;
        products.push({
          id,
          category: "iPhone",
          brand: "Apple",
          series: m.series,
          seriesOrder: m.order,
          name: m.series,
          color: c.ru,
          colorHex: c.hex,
          storage: st,
          watchSize: null,
          sim: "SIM + eSIM",
          region: "",
          images: [],
          thumbs: [],
          priceCash: cash,
          priceCard: cash ? Math.round((cash * CARD_RATIO) / 10) * 10 : 0,
          status: supplier ? "in_stock" : "preorder",
          badge: supplier ? "Новинка" : "",
          specs: specs18(m.isMax, st),
        });
        added++;
      }
    }
  }
  return added;
}

