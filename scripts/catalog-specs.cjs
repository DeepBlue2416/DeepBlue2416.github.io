function applyTemplates() {
  let touched = 0, addedKeys = 0;
  for (const p of products) {
    const t = T[p.series];
    if (!t) continue;
    const specs = Object.assign({}, p.specs || {});
    for (const [k, v] of Object.entries(t)) {
      const val = typeof v === "function" ? v(p) : v;
      if (val == null || val === "" || val === "—") continue;
      if (specs[k] !== val) addedKeys++;
      specs[k] = val;
    }
    p.specs = specs;
    touched++;
  }
  return { touched, addedKeys };
}

// ---------------------------------------------------------------------------
// 3. Память и размер корпуса в характеристиках у всех остальных товаров
// ---------------------------------------------------------------------------
function fillCommon() {
  let n = 0;
  for (const p of products) {
    if (!p.specs) p.specs = {};
    if (p.storage && p.storage !== "—" && !p.specs["Встроенная память"] && !p.specs["Накопитель"]) {
      p.specs["Встроенная память"] = p.storage; n++;
    }
    if (p.watchSize && !p.specs["Размер корпуса"]) { p.specs["Размер корпуса"] = p.watchSize; n++; }
    if (p.sim && p.sim !== "—" && !p.specs["Количество SIM-карт, шт"] && /SIM/i.test(p.sim) && p.category !== "Смарт-часы") {
      p.specs["Комплектация SIM"] = p.sim; n++;
    }
  }
  return n;
}

