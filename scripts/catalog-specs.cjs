// Округление до ближайшего X990 (как в парсере прайса).
function to990(n) {
  const down = Math.floor((n - 990) / 1000) * 1000 + 990;
  const up = down + 1000;
  return n - down <= up - n ? down : up;
}
const slug = (s) =>
  String(s).toLowerCase().replace(/ё/g, "e")
    .replace(/[а-я]/g, (c) => "a b v g d e j z i y k l m n o p r s t u f h c ch sh sh  y  e yu ya".split(" ")[c.charCodeAt(0) - 1072] || "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

